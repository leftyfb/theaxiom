def pdf_fixture():
    """A small two-page searchable PDF with a genuine xref and text streams."""
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R 4 0 R] /Count 2 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 400 500] /Resources << /Font << /F1 5 0 R >> >> /Contents 6 0 R >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 400 500] /Resources << /Font << /F1 5 0 R >> >> /Contents 7 0 R >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]
    for label in (b"alpha repeated alpha", b"beta alpha"):
        stream = b"BT /F1 18 Tf 40 420 Td (" + label + b") Tj ET\n"
        objects.append(b"<< /Length " + str(len(stream)).encode() + b" >>\nstream\n" + stream + b"endstream")
    data = b"%PDF-1.4\n"
    offsets = []
    for number, obj in enumerate(objects, 1):
        offsets.append(len(data))
        data += str(number).encode() + b" 0 obj\n" + obj + b"\nendobj\n"
    xref = len(data)
    data += b"xref\n0 " + str(len(objects) + 1).encode() + b"\n0000000000 65535 f \n"
    data += b"".join(f"{offset:010d} 00000 n \n".encode() for offset in offsets)
    return data + b"trailer\n<< /Size " + str(len(objects) + 1).encode() + b" /Root 1 0 R >>\nstartxref\n" + str(xref).encode() + b"\n%%EOF\n"


def epub_fixture():
    data = io.BytesIO()
    with zipfile.ZipFile(data, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("mimetype", "application/epub+zip", compress_type=zipfile.ZIP_STORED)
        archive.writestr("META-INF/container.xml", '<container xmlns="urn:oasis:names:tc:opendocument:xmlns:container"><rootfiles><rootfile full-path="OPS/book.opf" media-type="application/oebps-package+xml"/></rootfiles></container>')
        archive.writestr("OPS/book.opf", '<package xmlns="http://www.idpf.org/2007/opf" xmlns:dc="http://purl.org/dc/elements/1.1/" version="3.0"><metadata><dc:title>Fixture EPUB</dc:title><dc:creator>CI Author</dc:creator><dc:language>en</dc:language></metadata><manifest><item id="a" href="one.xhtml" media-type="application/xhtml+xml"/><item id="b" href="two.xhtml" media-type="application/xhtml+xml"/></manifest><spine><itemref idref="a"/><itemref idref="b"/></spine></package>')
        for filename, title in (("one.xhtml", "First isolated chapter"), ("two.xhtml", "Second isolated chapter")):
            archive.writestr("OPS/" + filename, '<html xmlns="http://www.w3.org/1999/xhtml"><body><h1>' + title + '</h1><p>Offline fixture text.</p></body></html>')
    return data.getvalue()


def seed(catalog, root):
    content = {"reader-pdf": ("pdf", pdf_fixture()), "reader-epub": ("epub", epub_fixture())}
    for sid, (kind, data) in content.items():
        if kind == "epub":
            assert len(epub_source.inspect(data)["chapters"]) == 2
        digest = hashlib.sha256(data).hexdigest()
        destination = root / "library" / kind
        destination.mkdir(parents=True, exist_ok=True)
        target = destination / f"{sid}.{digest}.{kind}"
        target.write_bytes(data)
        target.chmod(0o600)
        fields = dict(title=f"Fixture {kind.upper()}", format=kind,
                      provenance="Generated by isolated Chromium regression",
                      license="Synthetic test content",
                      expected_size_bytes=str(len(data)), sha256=digest)
        catalog.mutate("add", sid, fields, catalog.get()["revision"])
        publication.save(sid, True)
        adapter = pdf_source if kind == "pdf" else epub_source
        assert adapter.ready(adapter.pin(sid, catalog.get()["sources"][-1]["configuration"]))


def exercise(browser, base, viewport_name, viewport, artifact_dir):
    context = browser.new_context(viewport=viewport, accept_downloads=True)
    page = context.new_page()
    page.set_default_timeout(15000)
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    try:
        epub = base + "/api/library/epub/reader-epub"
        pdf = base + "/api/library/pdf/reader-pdf"
        # Real document is served only after fixture publication, not merely catalog registration.
        page.goto(epub)
        expect(page.locator("#chapter-content")).to_contain_text("First isolated chapter")
        expect(page.get_by_role("navigation", name="Chapter navigation")).to_contain_text("1 of 2")
        page.locator('nav[aria-label="Chapter navigation"] [data-chapter-nav="next"]').click()
        expect(page.locator("#chapter-content")).to_contain_text("Second isolated chapter")
        expect(page.locator('nav[aria-label="Chapter navigation"]')).to_contain_text("2 of 2")
        page.locator("details summary").click()
        expect(page.get_by_text("First isolated chapter", exact=True).last).to_be_visible()
        page.locator("details a").first.click()
        expect(page.locator("#chapter-content")).to_contain_text("First isolated chapter")
        page.get_by_role("link", name="Large").click()
        expect(page.locator("#chapter-content")).to_have_class("book large")
        page.keyboard.press("Tab")
        page.goto(epub + "/chapter/1?size=small")
        expect(page.locator("#chapter-content")).to_have_class("book small")
        expect(page.locator("#chapter-content")).to_contain_text("Second isolated chapter")
        expect(page.get_by_role("link", name="Return to library")).to_have_attribute("href", "/")
        with page.expect_download() as download:
            page.get_by_role("link", name="Download EPUB").click()
        assert download.value.suggested_filename.endswith(".epub")

        page.goto(pdf)
        expect(page.locator("#page")).to_have_value("1")
        expect(page.locator("#total")).to_contain_text("2")
        expect(page.locator("#message")).to_be_empty(timeout=20000)
        page.get_by_role("button", name="Next page").click()
        expect(page.locator("#page")).to_have_value("2")
        page.get_by_role("button", name="Previous page").click()
        expect(page.locator("#page")).to_have_value("1")
        page.get_by_role("button", name="Search document").click()
        expect(page.locator("#search-tools")).to_be_visible()
        page.locator("#find").fill("alpha")
        expect(page.locator("#matches")).to_contain_text("3", timeout=20000)
        page.get_by_role("button", name="Next match").click()
        expect(page.locator("#matches")).to_contain_text("of 3")
        page.get_by_role("button", name="Close search").click()
        expect(page.locator("#search-tools")).to_be_hidden()
        page.get_by_role("button", name="Zoom in").click()
        expect(page.locator("#paper")).to_be_visible()
        page.get_by_role("button", name="Page thumbnails").click()
        expect(page.locator("#thumbs")).to_be_visible()
        expect(page.locator("#thumbs button")).to_have_count(2)
        page.locator("#thumbs button").nth(1).click()
        expect(page.locator("#page")).to_have_value("2")
        page.get_by_role("link", name="Back to library").click()
        expect(page).to_have_url(base + "/")
        assert not errors, f"{viewport_name}: reader JS errors {errors}"
        print(f"PASS {viewport_name}: real PDF search/navigation and EPUB chapters/download")
    except Exception:
        artifact_dir.mkdir(parents=True, exist_ok=True)
        page.screenshot(path=str(artifact_dir / f"reader-{viewport_name}.png"), full_page=True)
        (artifact_dir / f"reader-{viewport_name}-errors.txt").write_text("\n".join(errors))
        raise
    finally:
        context.close()


def main():
    artifacts = Path(os.environ.get("AXIOM_BROWSER_ARTIFACTS", "/tmp/axiom-browser-artifacts"))
    pdfjs_root = Path(os.environ["AXIOM_TEST_PDFJS_ROOT"]).resolve()
    assert (pdfjs_root / "build/pdf.mjs").is_file(), "CI must install the pinned PDF.js build"
    with tempfile.TemporaryDirectory(prefix="axiom-reader-regression-") as tmp:
        root = Path(tmp)
        disk = root / "disk"
        for branch in ("staging", "library"):
            (disk / branch).mkdir(parents=True)
        with ExitStack() as stack:
            stack.enter_context(patch.object(storage_settings, "SETTINGS_PATH", root / "settings.json"))
            stack.enter_context(patch.object(admin_api, "PDFJS_ROOT", pdfjs_root))
            mount = storage._covering(disk, storage.read_mounts())
            stack.enter_context(patch.object(pdf_source, "LOCAL_FILESYSTEMS", {mount["type"]}))
            storage_settings.save_settings(dict(storage_settings.DEFAULT_SETTINGS, storage_root=str(disk)))
            catalog = catalog_store.CatalogStore(root / "sources.json")
            stack.enter_context(patch.object(admin_api, "SOURCE_CATALOG", catalog))
            stack.enter_context(patch.object(admin_api, "ADMIN_SESSIONS", admin_sessions.Sessions()))
            credential = root / "password"
            PasswordStore.initialize(credential, "fixture-password-not-production")
            seed(catalog, disk)
            server = admin_api.ThreadingHTTPServer(("127.0.0.1", 0), admin_api.AdminAPIHandler)
            host, port = server.server_address
            server.axiom_config = ServerConfig(host, port, frozenset({f"{host}:{port}"}),
                                               "admin", PasswordStore(credential))
            server.acquisition_monitor = SimpleNamespace(snapshot=lambda: {"stale": False, "acquisitions": []})
            worker = threading.Thread(target=server.serve_forever, daemon=True)
            worker.start()
            try:
                with sync_playwright() as playwright:
                    browser = playwright.chromium.launch(headless=True)
                    try:
                        for name, viewport in (("desktop", {"width": 1366, "height": 900}),
                                               ("mobile", {"width": 390, "height": 844})):
                            exercise(browser, f"http://{host}:{port}", name, viewport, artifacts)
                    finally:
                        browser.close()
            finally:
                server.shutdown()
                server.server_close()
                worker.join(timeout=5)


if __name__ == "__main__":
    main()
